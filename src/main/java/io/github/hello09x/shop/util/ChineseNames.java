    /**
     * 取物品中文名。没收录就退回英文美化名。
     */
    public static @NotNull String of(@NotNull Material material) {
        String name = NAMES.get(material.name());
        return name != null ? name : ItemSerializer.prettyName(material);
    }

    /**
     * 取某个商品应该显示的名字：
     * 优先用配置里写的 {@code name}（去掉颜色码），其次用中文名表
     */
    public static @NotNull String ofItem(@NotNull Material material, String configuredName) {
        if (configuredName != null && !configuredName.isBlank()) {
            return Text.strip(configuredName);
        }
        return of(material);
    }

    /** 是否收录了该材质的中文名 */
    public static boolean has(@NotNull Material material) {
        return NAMES.containsKey(material.name());
    }

